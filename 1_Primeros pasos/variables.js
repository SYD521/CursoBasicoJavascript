// var, variables globales
var saludo = 'Hola CIAPFA'
if (saludo) {
    var saludo = 'HOLA'
    console.log(saludo)
}
console.log(saludo)
// let, variables limitadas al alcance del bloque donde las definimos
let nombre = 'CIAPFA'
if (nombre) {
    let nombre = 'Alejo'
    console.log(nombre)
}
console.log(nombre)
// const, variables inmutables
const PI = 3.14
console.log(PI)